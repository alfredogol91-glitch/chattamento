export function localeFor(language) {
  return languages.find((item) => item.code === language)?.locale ?? 'en-GB';
}

export function getT(language = 'en') {
  const catalog = translations[language] ?? translations.en;
  return (key, params = {}) => {
    const value = catalog[key] ?? translations.en[key] ?? key;
    return value.replace(/\{(\w+)\}/g, (match, name) => params[name] == null ? match : String(params[name]));
  };
}
